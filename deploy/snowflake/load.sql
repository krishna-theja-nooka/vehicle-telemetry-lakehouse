-- Run in SnowSQL with an existing warehouse/database and role scoped to a demo schema.
-- Set file_path to one fact_trip Parquet file from a validated serving snapshot.
-- Example: snowsql -D file_path=/absolute/path/part-00000.parquet -f deploy/snowflake/load.sql
!set variable_substitution=true;
CREATE SCHEMA IF NOT EXISTS SYNTHETIC_FLEET;
USE SCHEMA SYNTHETIC_FLEET;
CREATE FILE FORMAT IF NOT EXISTS FLEET_PARQUET TYPE = PARQUET;
CREATE STAGE IF NOT EXISTS FLEET_STAGE FILE_FORMAT = FLEET_PARQUET;
PUT 'file://&file_path' @FLEET_STAGE AUTO_COMPRESS = FALSE;
CREATE TABLE IF NOT EXISTS FACT_TRIP (
    EVENT_ID STRING, VEHICLE_SK STRING, VEHICLE_ID STRING, DATE_KEY DATE,
    EVENT_TS TIMESTAMP_NTZ, REGION STRING, ROUTE_ID STRING,
    DISTANCE_KM FLOAT, DURATION_MIN FLOAT, ENERGY_KWH FLOAT
);
COPY INTO FACT_TRIP FROM @FLEET_STAGE
    FILE_FORMAT = (FORMAT_NAME = FLEET_PARQUET)
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = ABORT_STATEMENT;
SELECT REGION, SUM(DISTANCE_KM) AS KM,
    100 * SUM(ENERGY_KWH) / NULLIF(SUM(DISTANCE_KM), 0) AS KWH_PER_100KM
FROM FACT_TRIP GROUP BY REGION;
